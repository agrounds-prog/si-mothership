/* SIGNAL SEQUENCE Phase 2: geometry, survival, relay and private UI. */
const assert=require("node:assert/strict");
const S=require("../signal-sequence.js");
for(const n of [4,6,8]){
 const g=S.make({pilot:"Teacher",signals:n,sound:true});
 assert.equal(S.count(g),n);
 const project=S.sharedHTML(g,true),student=S.studentHTML(g,"Teacher");
 assert.equal((project.match(/data-ss-pad=/g)||[]).length,n);
 assert.equal((student.match(/data-ss-pad=/g)||[]).length,n);
 assert.match(project,new RegExp(n+" colored"));
 S.startRound(g,{now:1000,random:()=>.9999});
 assert.equal(g.sequence[0],n-1);
 assert.equal(S.cue(g,1750),n-1);
 assert.equal(S.beginInput(g,g.playbackEnd+1),true);
 assert.equal((S.studentHTML(g,"Teacher").match(/data-ss-press=/g)||[]).length,n*2);
 assert.equal(S.press(g,n-1).correct,true);
 console.log("PASS "+n+"-color projector/student geometry and tapping");
}
const survival=S.make({mode:"survival",signals:8,participants:["Ada","Beck","Cal"],speed:"slow"});
assert.equal(survival.mode,"survival");
assert.equal(S.startRound(survival,{now:1000,random:()=>.18}),true);
assert.deepEqual(survival.sequence,[1]);
assert.equal(S.beginInput(survival,survival.playbackEnd+1),true);
assert.equal(S.canPlay(survival,"Ada"),true);
assert.equal(S.canPlay(survival,"Teacher"),false);
assert.equal((S.studentHTML(survival,"Ada").match(/data-ss-press=/g)||[]).length,16);
assert.equal((S.studentHTML(survival,"Other").match(/data-ss-press=/g)||[]).length,0);
assert.equal(S.pressFor(survival,"Ada",1).correct,true);
assert.equal(survival.entries.Ada.status,"cleared");
assert.equal(survival.phase,"input");
assert.equal(S.pressFor(survival,"Beck",7).correct,false);
assert.equal(survival.entries.Beck.status,"out");
assert.equal(S.canPlay(survival,"Beck"),false);
assert.equal(S.pressFor(survival,"Beck",1).error,"Input is locked.");
assert.equal(S.pressFor(survival,"Cal",1).correct,true);
assert.equal(survival.phase,"success");
assert.deepEqual(S.alive(survival),["Ada","Cal"]);
S.startRound(survival,{now:5000,random:()=>.99});
assert.deepEqual(survival.sequence,[1,7]);
assert.equal(survival.entries.Beck.status,"out");
assert.equal(S.beginInput(survival,survival.playbackEnd+1),true);
assert.equal(S.pressFor(survival,"Ada",1).finished,false);
assert.equal(S.playerProgress(survival,"Ada"),1);
assert.equal(S.pressFor(survival,"Ada",7).finished,false);
assert.equal(S.pressFor(survival,"Cal",1).finished,false);
assert.equal(S.pressFor(survival,"Cal",7).finished,true);
assert.equal(survival.phase,"success");
assert.equal(survival.best,2);
S.retry(survival);
assert.equal(survival.round,0);
assert.equal(survival.best,2);
assert.equal(S.alive(survival).length,3);
console.log("PASS Crew Survival independent progress, elimination, next round, retry");
const relay=S.make({mode:"relay",signals:6,participants:["Ada","Beck","Cal"]});
S.startRound(relay,{now:1000,random:()=>.99});
S.beginInput(relay,relay.playbackEnd+1);
assert.equal(relay.pilot,"Ada");
assert.equal(S.pressFor(relay,"Beck",5).error,"Input is locked.");
assert.equal(S.pressFor(relay,"Ada",5).finished,true);
S.startRound(relay,{now:4500,random:()=>.49});
S.beginInput(relay,relay.playbackEnd+1);
assert.equal(S.pressFor(relay,"Ada",5).finished,false);
assert.equal(relay.pilot,"Beck");
assert.equal(S.canPlay(relay,"Ada"),false);
assert.equal(S.canPlay(relay,"Beck"),true);
assert.equal(S.pressFor(relay,"Beck",2).finished,true);
assert.equal(relay.phase,"success");
assert.match(S.sharedHTML(relay,true),/TEAM RELAY/);
S.retry(relay);
assert.deepEqual(relay.participants,["Ada","Beck","Cal"]);
console.log("PASS Team Relay passes each signal and denies inactive pilots");
assert.throws(()=>S.make({mode:"survival",participants:["Ada"]}),/two students/);
assert.throws(()=>S.make({mode:"relay",participants:[]}),/two students/);
assert.match(S.setupHTML(["Ada","Beck"]),/id="ssMode"/);
assert.match(S.setupHTML(["Ada","Beck"]),/id="ssSignals"/);
console.log("SIGNAL SEQUENCE Phase 2 engine complete");
